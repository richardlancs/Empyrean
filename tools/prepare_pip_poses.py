"""Turn Codex-generated Pip poses into clean page assets (design tooling).

Input: transparent PNGs generated by Codex's built-in image tool from the Pip
reference sheet (prompts recorded in docs/dashboard-redesign/pip/README.md).
For each pose: keep the character's shapes (every alpha component at least 1 %
of the largest, so the peeking paws survive) and drop specks; make near-opaque
body pixels fully opaque; crop with even padding (none under the peek's straight
cut, so it sits flush on the frame edge); resize on premultiplied colour so
edges get no dark halo. Output is about twice the displayed size.

    python tools/prepare_pip_poses.py IN_DIR OUT_DIR
"""

from __future__ import annotations

import sys
from pathlib import Path

import cv2
import numpy as np

# output name: (generated file, output height in pixels, keep the bottom edge flush)
POSES = {
    "pip-recline": ("gen-recline.png", 112, False),
    "pip-peek-edge": ("gen-peek.png", 80, True),
    "pip-wait": ("gen-wait.png", 120, False),
    "pip-concerned": ("gen-concerned.png", 120, False),
}
PADDING = 0.04
OPAQUE_FROM = 200
MIN_SHARE = 0.01


def clean(image: np.ndarray, height: int, flush_bottom: bool) -> np.ndarray:
    """Return the cropped, de-specked and resized RGBA pose."""
    alpha = image[:, :, 3]
    _count, labels, stats, _ = cv2.connectedComponentsWithStats((alpha > 8).astype(np.uint8), 8)
    areas = stats[1:, cv2.CC_STAT_AREA]
    keep = [i + 1 for i, a in enumerate(areas) if a >= areas.max() * MIN_SHARE]
    mask = np.isin(labels, keep)
    out = image.copy()
    out[~mask] = 0
    a = out[:, :, 3]
    a[a >= OPAQUE_FROM] = 255
    ys, xs = np.nonzero(mask)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    pad = round(max(y1 - y0, x1 - x0) * PADDING)
    crop = out[y0:y1, x0:x1]
    crop = cv2.copyMakeBorder(crop, pad, 0 if flush_bottom else pad, pad, pad, cv2.BORDER_CONSTANT, value=0)
    width = round(crop.shape[1] * height / crop.shape[0])
    rgb = crop[:, :, :3].astype(np.float32) * (crop[:, :, 3:4].astype(np.float32) / 255)
    rgb = cv2.resize(rgb, (width, height), interpolation=cv2.INTER_AREA)
    al = cv2.resize(crop[:, :, 3].astype(np.float32), (width, height), interpolation=cv2.INTER_AREA)
    safe = np.maximum(al, 1e-3)[:, :, None] / 255
    rgb = np.where(al[:, :, None] > 0, rgb / safe, 0)
    return np.dstack([np.clip(rgb, 0, 255), np.clip(al, 0, 255)]).round().astype(np.uint8)


def main(src: Path, dest: Path) -> None:
    """Prepare every pose in POSES from src into dest."""
    dest.mkdir(parents=True, exist_ok=True)
    for name, (file, height, flush) in POSES.items():
        image = cv2.imread(str(src / file), cv2.IMREAD_UNCHANGED)
        if image is None or image.shape[2] != 4:
            raise SystemExit(f"{file}: missing or has no transparency")
        result = clean(image, height, flush)
        cv2.imwrite(str(dest / f"{name}.png"), result, [cv2.IMWRITE_PNG_COMPRESSION, 9])
        print(f"{name}.png {result.shape[1]} x {result.shape[0]}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
